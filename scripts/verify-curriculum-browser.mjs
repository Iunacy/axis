import { mkdirSync } from "node:fs";
import assert from "node:assert/strict";
import { Chess } from "chess.js";
import { checkBoardFocus } from "./check-board-focus.mjs";
import { chromium } from "playwright";
mkdirSync("output/playwright", { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH, args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const origin = process.env.AXIS_SMOKE_URL || "http://localhost:3000";
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const readState = () => page.evaluate(() => new Promise((resolve, reject) => {
  const request = indexedDB.open("axis", 1);
  request.onerror = () => reject(request.error);
  request.onsuccess = () => {
    const db = request.result, row = db.transaction("state").objectStore("state").get("cc:store");
    row.onsuccess = () => { db.close(); resolve(JSON.parse(row.result).state); };
    row.onerror = () => reject(row.error);
  };
}));
const fit = async () => assert.ok(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight + 1 && document.documentElement.scrollWidth <= innerWidth + 1));
try {
  await page.goto(origin + "/training");
  await page.getByRole("button", { name: "Your learning plan", exact: true }).click();
  const plan = page.getByRole("dialog", { name: "Your learning plan", exact: true });
  await plan.getByText(/0 distinct reviewed games/).waitFor();
  assert.equal(await plan.getByText("Recurring", { exact: true }).count(), 0);
  await page.keyboard.press("Escape");
  await page.goto(origin + "/games");
  await page.getByRole("textbox", { name: "Paste PGN here" }).fill('[Event "Curriculum smoke"]\n[White "Study"]\n[Black "Curriculum game"]\n[Result "0-1"]\n\n1. f3 e5 2. g4 Qh4# 0-1');
  await page.getByRole("button", { name: "Import games", exact: true }).click();
  await page.getByRole("link", { name: "Curriculum game", exact: true }).click();
  await page.getByText("Cached review · verification complete", { exact: true }).waitFor({ timeout: 90000 });
  await page.goto(origin + "/training");
  await page.locator(".axis-training-stage").waitFor();
  await fit();
  const reveal = page.getByRole("button", { name: "Show solution", exact: true });
  assert.ok(await reveal.isDisabled(), "answers require an attempt or progressively revealed hints");
  const initial = await readState();
  await checkBoardFocus(page, "training");
  assert.deepEqual(await readState(), initial, "fullscreen cannot mutate learning state");
  const chosen = initial.trainingSession.skillId === "king-safety" ? { id: "opening-decisions", title: "Opening decisions" } : { id: "king-safety", title: "King safety" };
  await page.getByRole("button", { name: "Your learning plan", exact: true }).click();
  await plan.getByText(/1 distinct reviewed games/).waitFor();
  assert.equal(await plan.getByText("Recurring", { exact: true }).count(), 0);
  await plan.locator(".axis-curriculum-item").filter({ has: page.getByText(chosen.title, { exact: true }) }).locator("summary").click();
  await plan.locator(".axis-curriculum-item").filter({ has: page.getByText(chosen.title, { exact: true }) }).getByRole("button", { name: "Use for next session", exact: true }).click();
  await page.getByText(`Next session: ${chosen.title}`, { exact: true }).waitFor();
  let state = await readState();
  assert.equal(state.curriculumPreference, chosen.id);
  const id = state.trainingSession.active.puzzleId;
  const puzzle = state.puzzles.find(row => row.id === id);
  const line = puzzle.solution_lines_uci?.[0] ?? (() => {
    const chess = new Chess(puzzle.fen), moves = [];
    const append = san => { const move = chess.move(san); moves.push(`${move.from}${move.to}${move.promotion ?? ""}`); };
    puzzle.solution_san.forEach((san,index) => { append(san); if(index+1<puzzle.solution_san.length) append(puzzle.reply_san[index]); });
    return moves;
  })();
  const board = page.getByRole("group", { name: "Chessboard", exact: true });
  for (let i = 0; i < line.length; i += 2) {
    const move = line[i];
    await board.getByRole("button", { name: move.slice(0,2), exact: true }).click();
    await board.getByRole("button", { name: move.slice(2,4), exact: true }).click();
    if (i + 2 < line.length) await page.getByText(new RegExp(`move ${i / 2 + 2} of`)).waitFor();
  }
  await page.locator(".axis-puzzle-result").waitFor();
  await page.getByText(/Recorded candidate:/).waitFor();
  await page.screenshot({ path: "output/playwright/v4-training.png" });
  await page.reload();
  await page.locator(".axis-puzzle-result").waitFor();
  state = await readState();
  const beforeHistory = await readState();
  await page.getByRole("button", { name: "History", exact: true }).click();
  await page.getByRole("dialog", { name: "History", exact: true }).waitFor();
  await page.keyboard.press("Escape");
  assert.deepEqual(await readState(), beforeHistory, "progress drawer cannot mutate the active attempt");
  const saved = state.puzzles.find(row => row.id === id);
  assert.equal(saved.reviews.length, 1, "reload cannot duplicate solve evidence");
  assert.equal(saved.reviews[0].solved, true);
  assert.equal(saved.reviews[0].hintsUsed, 0);
  assert.ok(saved.due_at);
  assert.equal(state.curriculumPreference, chosen.id);
  await page.getByRole("button", { name: "Your learning plan", exact: true }).click();
  const safety = plan.locator(".axis-curriculum-item").filter({ has: page.getByText(chosen.title, { exact: true }) });
  if (!await safety.evaluate(el => el.open)) await safety.locator("summary").click();
  await safety.getByText(/No reliable comparison yet/).waitFor();
  assert.equal(await plan.getByText(/Practice criterion met/).count(), 0);
  await page.screenshot({ path: "output/playwright/v4-plan.png" });
  await safety.getByRole("button", { name: "Read focused lesson", exact: true }).click();
  const lesson = page.getByRole("dialog", { name: "Focused lesson", exact: true });
  await lesson.getByRole("heading", { name: chosen.title, exact: true }).waitFor();
  await lesson.getByText(/Reading this guide earns no mastery credit/).waitFor();
  assert.equal(await lesson.getByRole("button", { name: /Mark.*completed/ }).count(), 0);
  await page.screenshot({ path: "output/playwright/v4-lesson.png" });
  await page.keyboard.press("Escape");
  await plan.waitFor();
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 1280, height: 720 }); await fit();
  assert.ok((await page.locator(".axis-training-stage .axis-board-root").boundingBox()).width >= 380, "laptop board remains usable without fullscreen");
  await page.screenshot({ path: "output/playwright/v4-training-720.png" });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: "output/playwright/v4-training-mobile.png" });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(origin + "/dashboard");
  await page.getByText(/sample is still limited/).waitFor(); await fit();
  await page.locator("main").evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)));
  await page.screenshot({ path: "output/playwright/v4-dashboard.png" });
  await page.goto(origin + "/lessons");
  await page.getByRole("button", { name: "Generate lessons from my weaknesses", exact: true }).click();
  await page.locator(".axis-lesson-link").first().click();
  await page.locator(".axis-focus-lesson").first().waitFor();
  await checkBoardFocus(page, "lesson");
  assert.deepEqual(errors, []);
  console.log("PASS: empty/sparse curriculum, real engine evidence, preserved override/session, interactive solution, recorded evidence, reload, review scheduling, honest transfer/mastery, desktop/mobile layout");
} catch (error) {
  await page.screenshot({ path: "output/playwright/v4-failure.png" }).catch(() => {});
  throw error;
} finally { await browser.close(); }
